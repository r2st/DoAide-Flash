import { v4 as uuid } from 'uuid';
import type { Card, Deck } from '../lib/types';

function makeCard(front: string, back: string, category?: string): Card {
  return {
    id: uuid(),
    front,
    back,
    category,
    ease: 2.5,
    interval: 0,
    repetitions: 0,
    nextReview: 0,
  };
}

function makeDeck(title: string, description: string, tags: string[], cards: [string, string, string?][]): Deck {
  return {
    id: `builtin-${title.toLowerCase().replace(/\s+/g, '-')}`,
    title,
    description,
    tags,
    cards: cards.map(([f, b, c]) => makeCard(f, b, c)),
    createdAt: Date.now(),
    updatedAt: Date.now(),
    isBuiltIn: true,
  };
}

